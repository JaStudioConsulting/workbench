async function createCase(db, key = "after_call:sourcing:7:42", caseType = "after_call") {
  return (await db.query(`
    INSERT INTO public.operator_cases (case_key, case_type, title)
    VALUES ($1, $2, 'Synthetic case') RETURNING id, owner_id
  `, [key, caseType])).rows[0];
}

async function addSource(db, caseId, sourceType, sourceId, status = "confirmed", required = true) {
  const caseKey = (await db.query("SELECT case_key FROM public.operator_cases WHERE id=$1", [caseId])).rows[0].case_key;
  const identity = /^after_call:(sourcing|submission):([1-9]\d*):([1-9]\d*)$/.exec(caseKey);
  const dailyIdentity = /^daily:candidate_review_actions:([1-9]\d*)$/.exec(caseKey);
  if ((identity && sourceId === `${identity[1]}:${identity[2]}`) || (caseKey.startsWith("mpc:") && /^([a-z_]+:[1-9]\d*|manual:[0-9a-f-]{36})$/i.test(sourceId)) || (dailyIdentity && sourceType === "candidate")) {
    if (sourceType === "candidate" && status !== "missing") {
    await db.query("INSERT INTO public.candidates_all (id) VALUES ($1) ON CONFLICT DO NOTHING", [sourceId]);
    }
  }
  if ((identity && sourceType === "job" && sourceId === identity[3]) || (dailyIdentity && sourceType === "job")) {
    await db.query("INSERT INTO public.tracker_jobs (job_id) VALUES ($1) ON CONFLICT DO NOTHING", [sourceId]);
  }
  if (identity && ["transcript", "notes"].includes(sourceType) && /^[0-9a-f-]{36}$/i.test(sourceId)) {
    await db.query(`
      INSERT INTO public.meeting_drafts (id,owner_id,job_id,candidate_source,candidate_source_id,transcript,notes)
      VALUES ($1,$2,$3,$4,$5,'Saved transcript','Saved notes') ON CONFLICT DO NOTHING
    `, [sourceId, first, identity[3], identity[1], identity[2]]);
  }
  const sourceSystem = sourceType === "candidate" || sourceType === "job" ? "supabase_tracker"
    : sourceType === "transcript" || sourceType === "notes" ? "meeting_drafts"
      : sourceType === "draft" && dailyIdentity ? "candidate_review_actions" : "human_review";
  return (await db.query(`
    INSERT INTO public.case_sources (case_id, source_type, source_system, source_id, label, evidence_status, required, metadata, observed_at)
    VALUES ($1, $2, $6, $3, $2, $4, $5,
      CASE WHEN $2 IN ('resume','client','communication','draft') THEN jsonb_build_object('reviewedBy',$7::text) ELSE '{}'::jsonb END,
      CASE WHEN $2 IN ('resume','client','communication','draft') THEN now() ELSE NULL END) RETURNING id
  `, [caseId, sourceType, sourceId, status, required, sourceSystem, first])).rows[0].id;
}

async function addArtifact(db, caseId, content = { text: "Draft" }, sourceRef = "meeting-1:v1", artifactType = "presentation_email", generatedBy = "local_draft_preparer") {
  return (await db.query(`
    INSERT INTO public.case_artifacts (case_id, artifact_type, source_ref, content, generated_by)
    VALUES ($1, $4, $2, $3, $5) RETURNING id, created_at, updated_at, content, case_id, artifact_type, owner_id
  `, [caseId, sourceRef, JSON.stringify(content), artifactType, generatedBy])).rows[0];
}

function manifestFor(caseId, artifact, operation = "create_draft_only", execution, requiredSources = ["candidate", "job", "transcript"]) {
  return {
    caseId,
    artifactId: artifact.id,
    artifactVersion: artifact.created_at,
    contentSnapshot: artifact.content,
    requiredSources,
    operation,
    ...(execution ? { execution } : {}),
  };
}

async function addAction(db, caseId, artifact, key = "synthetic-action-0001", actionType = "gmail_draft", operation = "create_draft_only", execution, requiredSources) {
  return (await db.query(`
    INSERT INTO public.case_actions (case_id, action_type, idempotency_key, manifest)
    VALUES ($1, $4, $2, $3) RETURNING id
  `, [caseId, key, JSON.stringify(manifestFor(caseId, artifact, operation, execution, requiredSources)), actionType])).rows[0];
}

async function approveArtifact(db, artifactId) {
  await db.query("UPDATE public.case_artifacts SET review_state = 'approved', reviewed_at = now() WHERE id = $1", [artifactId]);
}

async function approveAction(db, actionId) {
  await db.query("UPDATE public.case_actions SET approval_state = 'approved', approved_at = now() WHERE id = $1", [actionId]);
}

