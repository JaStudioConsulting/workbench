test("inserting a newer artifact version withdraws prior approval and prevents stale reapproval", async () => {
  const db = await createDatabase();
  try {
    const record = await createCase(db);
    await addSource(db, record.id, "candidate", "sourcing:7");
    await addSource(db, record.id, "job", "42");
    await addSource(db, record.id, "transcript", meetingId);
    const original = await addArtifact(db, record.id, { body: "Approved content" }, "mpc:outreach:v1");
    const action = await addAction(db, record.id, original);
    await approveArtifact(db, original.id);
    await approveAction(db, action.id);
    const before = (await db.query("SELECT reviewed_at FROM public.case_artifacts WHERE id=$1", [original.id])).rows[0];
    const approvedAction = (await db.query("SELECT approved_at,manifest FROM public.case_actions WHERE id=$1", [action.id])).rows[0];

    const latest = await addArtifact(db, record.id, { body: "Revised content" }, "mpc:outreach:v2");
    const prior = (await db.query("SELECT review_state,reviewed_at FROM public.case_artifacts WHERE id=$1", [original.id])).rows[0];
    const withdrawn = (await db.query("SELECT approval_state,approved_at,manifest FROM public.case_actions WHERE id=$1", [action.id])).rows[0];
    assert.equal(prior.review_state, "rejected");
    assert.equal(new Date(prior.reviewed_at).getTime(), new Date(before.reviewed_at).getTime());
    assert.equal(withdrawn.approval_state, "rejected");
    assert.equal(new Date(withdrawn.approved_at).getTime(), new Date(approvedAction.approved_at).getTime());
    assert.deepEqual(withdrawn.manifest, approvedAction.manifest);
    assert.equal((await db.query("SELECT review_state FROM public.case_artifacts WHERE id=$1", [latest.id])).rows[0].review_state, "draft");
    await assert.rejects(approveArtifact(db, original.id), /superseded artifact versions cannot be approved/i);

    await approveArtifact(db, latest.id);
    const replacementAction = await addAction(db, record.id, latest, "synthetic-action-0002");
    await approveAction(db, replacementAction.id);
    assert.equal((await db.query("SELECT approval_state FROM public.case_actions WHERE id=$1", [replacementAction.id])).rows[0].approval_state, "approved");

    assert.equal((await db.query("SELECT has_table_privilege('authenticated','public.case_artifact_supersessions','SELECT') AS can_read")).rows[0].can_read, false);
    assert.equal((await db.query("SELECT has_table_privilege('authenticated','public.case_artifact_supersessions','INSERT') AS can_insert")).rows[0].can_insert, false);
  } finally { await db.close(); }
});

