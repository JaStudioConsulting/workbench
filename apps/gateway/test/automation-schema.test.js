test("reverting A to B to A creates a fresh current generation", async () => {
  const db = await createDatabase();
  try {
    await setFields(db, { workStatus: "A" });
    await reconcile(db);
    const a = await current(db);
    await setFields(db, { workStatus: "B" });
    assert.equal(await reconcile(db), 1);
    const b = await current(db);
    await setFields(db, { workStatus: "A" });
    assert.equal(await reconcile(db), 1);
    const restored = await current(db);
    assert.equal(restored.source_hash, a.source_hash);
    assert.notEqual(restored.id, a.id);
    assert.notEqual(restored.id, b.id);
    assert.equal((await db.query("SELECT state FROM public.automation_jobs WHERE id=$1", [b.id])).rows[0].state, "outdated");
    assert.equal(await reconcile(db), 0);
    assert.equal((await claim(db)).id, restored.id);
  } finally { await db.close(); }
});

