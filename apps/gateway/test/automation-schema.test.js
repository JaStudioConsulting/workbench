async function createDatabase() {
  const db = new PGlite();
  try {
    await db.exec(`
      CREATE ROLE anon;
      CREATE ROLE authenticated;
      CREATE SCHEMA auth;
      CREATE TABLE auth.users (id uuid PRIMARY KEY);
      CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS
        $$ SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      CREATE FUNCTION public.is_authorized_recruiter() RETURNS boolean LANGUAGE sql STABLE AS
        $$ SELECT auth.uid() IN ('${first}'::uuid, '${second}'::uuid) $$;
      ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO authenticated, anon;
      CREATE TABLE public.candidates_all (
        id text PRIMARY KEY, candidate_source text NOT NULL, candidate_name text NOT NULL,
        current_title text, owner_id uuid, edited_at timestamptz
      );
      ALTER TABLE public.candidates_all ENABLE ROW LEVEL SECURITY;
      CREATE POLICY candidate_access ON public.candidates_all TO authenticated
        USING (candidate_source <> 'manual' OR owner_id = auth.uid());
      CREATE TABLE public.candidates_manual (id uuid PRIMARY KEY, owner_id uuid NOT NULL);
      ALTER TABLE public.candidates_manual ENABLE ROW LEVEL SECURITY;
      CREATE POLICY manual_owner ON public.candidates_manual TO authenticated USING (owner_id = auth.uid());
      CREATE TABLE public.tracker_jobs (job_id bigint PRIMARY KEY, job_title text, status text);
      CREATE TABLE public.meeting_drafts (
        id uuid PRIMARY KEY DEFAULT gen_random_uuid(), owner_id uuid NOT NULL DEFAULT auth.uid(),
        job_id bigint NOT NULL, candidate_source text NOT NULL CHECK (candidate_source IN ('sourcing','submission')),
        candidate_source_id bigint NOT NULL, transcript text NOT NULL DEFAULT '', notes text NOT NULL DEFAULT '',
        created_at timestamptz NOT NULL DEFAULT now(), recording_id text,
        transcription_status text NOT NULL DEFAULT 'ready' CHECK (transcription_status IN ('pending','ready','failed'))
      );
      ALTER TABLE public.meeting_drafts ENABLE ROW LEVEL SECURITY;
      CREATE POLICY meeting_owner ON public.meeting_drafts TO authenticated
        USING (owner_id=auth.uid()) WITH CHECK (owner_id=auth.uid());
      CREATE TABLE public.candidate_review_actions (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, job_id bigint NOT NULL,
        candidate_source text NOT NULL, candidate_source_id bigint NOT NULL,
        action_type text NOT NULL, activity_type text NOT NULL DEFAULT '', note text NOT NULL DEFAULT '',
        status text NOT NULL CHECK (status IN ('saved','waiting_for_loxo','failed','user_reported')),
        created_at timestamptz NOT NULL DEFAULT now()
      );
      GRANT USAGE ON SCHEMA public, auth TO authenticated;
      INSERT INTO auth.users(id) VALUES ('${first}'),('${second}');
      INSERT INTO public.candidates_all(id,candidate_source,candidate_name,current_title)
        VALUES ('sourcing:7','sourcing','Test candidate','Technician');
      INSERT INTO public.tracker_jobs VALUES (42,'Test job','Active');
    `);
    for (const name of [
      "023_operator_cases.sql", "027_operator_case_history_privileges.sql",
      "028_mpc_case_artifact_prerequisites.sql", "029_supersede_operator_artifact_approvals.sql",
      "031_save_operator_artifact_revision.sql", "032_no_ai_automation.sql",
      "033_automation_interactive_priority.sql",
    ]) await db.exec(await readFile(new URL(`../migrations/${name}`, import.meta.url), "utf8"));
    await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [first]);
    await db.exec("SET ROLE authenticated");
    return db;
  } catch (error) {
    await db.close();
    throw error;
  }
}

async function asAdmin(db, sql, params = []) {
  await db.exec("RESET ROLE");
  try { return await db.query(sql, params); }
  finally { await db.exec("SET ROLE authenticated"); }
}
async function reconcile(db) {
  return (await db.query("SELECT public.reconcile_workbench_automation() AS count")).rows[0].count;
}
async function claim(db) {
  return (await db.query("SELECT * FROM public.claim_workbench_automation()")).rows[0];
}
async function current(db, key = recordKey) {
  return (await db.query("SELECT a.* FROM public.automation_jobs a JOIN public.automation_current c ON c.job_id=a.id AND c.owner_id=a.owner_id WHERE c.record_key=$1", [key])).rows[0];
}
async function setFields(db, value) {
  await db.query("INSERT INTO public.automation_inputs(candidate_id,fields) VALUES ('sourcing:7',$1) ON CONFLICT(owner_id,candidate_id) DO UPDATE SET fields=excluded.fields", [JSON.stringify(value)]);
}
async function finish(db, task, text = "Saved explicit fields", status = { needsInformation: false }, outputs) {
  const body = outputs || [{ type: "candidate_submission", content: { text } }];
  return (await db.query("SELECT public.finish_workbench_automation($1,$2,$3,$4) AS case_id", [task.id, task.lease_token, JSON.stringify(body), JSON.stringify(status)])).rows[0].case_id;
}
async function addMeeting(db) {
  return (await db.query("INSERT INTO public.meeting_drafts(job_id,candidate_source,candidate_source_id,notes,transcription_status) VALUES (42,'sourcing',7,'Recorded notes','disabled') RETURNING *")).rows[0];
}

