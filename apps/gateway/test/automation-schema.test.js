test("automatic retries stop after four attempts and explicit retry resets the budget", async () => {
  const db = await createDatabase();
  try {
    await reconcile(db);
    let last;
    for (let attempt = 1; attempt <= 4; attempt += 1) {
      last = await claim(db);
      assert.equal(last.attempts, attempt);
      await db.query("SELECT public.fail_workbench_automation($1,$2,'Test failure')", [last.id, last.lease_token]);
      assert.equal((await current(db)).state, attempt < 4 ? "queued" : "failed");
      if (attempt < 4) await asAdmin(db, "UPDATE public.automation_jobs SET available_at=now()-interval '1 second' WHERE id=$1", [last.id]);
    }
    assert.equal(await claim(db), undefined);
    assert.equal((await db.query("SELECT public.retry_workbench_automation($1) AS retried", [last.id])).rows[0].retried, true);
    assert.equal((await claim(db)).attempts, 1);
  } finally { await db.close(); }
});

test("new automated versions preserve human edits and withdraw old approvals", async () => {
  const db = await createDatabase();
  try {
    await reconcile(db);
    const original = await claim(db);
    const caseId = await finish(db, original, "First template");
    const initial = (await db.query("SELECT * FROM public.case_artifacts WHERE case_id=$1", [caseId])).rows[0];
    const edited = (await db.query("SELECT public.save_operator_artifact_revision($1,$2,$3) AS artifact", [initial.id, initial.updated_at, JSON.stringify({ text: "Human-approved wording" })])).rows[0].artifact;
    await db.query("UPDATE public.case_artifacts SET review_state='approved',reviewed_at=now() WHERE id=$1", [edited.id]);
    await setFields(db, { workStatus: "Explicit update" });
    await reconcile(db);
    const refreshed = await claim(db);
    assert.equal(await finish(db, refreshed, "Updated template"), caseId);
    const savedHuman = (await db.query("SELECT * FROM public.case_artifacts WHERE id=$1", [edited.id])).rows[0];
    assert.deepEqual(savedHuman.content, { text: "Human-approved wording" });
    assert.equal(savedHuman.review_state, "rejected");
    const newest = (await db.query("SELECT * FROM public.case_artifacts WHERE source_ref=$1", [`automation:${refreshed.id}`])).rows[0];
    assert.equal(newest.review_state, "draft");
    await assert.rejects(db.query("UPDATE public.case_artifacts SET review_state='approved',reviewed_at=now() WHERE id=$1", [edited.id]), /Superseded artifact/);
  } finally { await db.close(); }
});

test("removed or mismatched structured resumes withdraw the current output while retaining human history", async (t) => {
  for (const change of ["removed", "name mismatch"]) await t.test(change, async () => {
    const db = await createDatabase();
    try {
      const source = {
        name: { value: "Test candidate", evidence: [{ source: "resume", quote: "Test candidate" }] },
        title: { value: "Technician", evidence: [{ source: "resume", quote: "Technician" }] },
        summary: [],
        skills: [
          { text: "Maintenance", evidence: [{ source: "resume", quote: "Maintenance" }] },
          { text: "Repair", evidence: [{ source: "resume", quote: "Repair" }] },
        ],
        experience: [], education: [], certifications: [], additionalInformation: [],
      };
      await db.query("INSERT INTO public.automation_inputs(candidate_id,resume) VALUES ('sourcing:7',$1)", [JSON.stringify(source)]);
      await reconcile(db);
      const initialTask = await claim(db);
      const firstDrafts = await assembleTemplates(initialTask.payload, { renderer: async () => ({ fileName: "saved.pdf" }) });
      const caseId = await finish(db, initialTask, "", firstDrafts.result, firstDrafts.outputs);
      const initial = (await db.query("SELECT * FROM public.case_artifacts WHERE case_id=$1 AND artifact_type='branded_resume'", [caseId])).rows[0];
      const humanContent = { ...initial.content, text: "Human-reviewed resume wording" };
      const edited = (await db.query("SELECT public.save_operator_artifact_revision($1,$2,$3) AS artifact", [initial.id, initial.updated_at, JSON.stringify(humanContent)])).rows[0].artifact;
      await db.query("UPDATE public.case_artifacts SET review_state='approved',reviewed_at=now() WHERE id=$1", [edited.id]);

      if (change === "removed") await db.query("UPDATE public.automation_inputs SET resume=NULL WHERE candidate_id='sourcing:7'");
      else await asAdmin(db, "UPDATE public.candidates_all SET candidate_name='Corrected candidate identity' WHERE id='sourcing:7'");
      assert.equal(await reconcile(db), 1);
      const currentTask = await claim(db);
      const currentDrafts = await assembleTemplates(currentTask.payload, { renderer: async () => { throw new Error("A stale resume must not render"); } });
      assert.equal(currentDrafts.outputs.some((output) => output.type === "branded_resume"), false);
      assert.equal(currentDrafts.result.resumeStatus, "needs_information");
      if (change === "name mismatch") assert.ok(currentDrafts.result.missing.includes("structuredResumeIdentity"));
      assert.equal(await finish(db, currentTask, "", currentDrafts.result, currentDrafts.outputs), caseId);

      const versions = (await db.query("SELECT * FROM public.case_artifacts WHERE case_id=$1 AND artifact_type='branded_resume' ORDER BY created_at DESC,id DESC", [caseId])).rows;
      assert.equal(versions.length, 3);
      const latest = versions[0];
      assert.equal(latest.source_ref, `automation:${currentTask.id}`);
      assert.equal(latest.content.status, "needs_information");
      assert.equal(latest.content.pdf, undefined);
      assert.equal(latest.content.sections, undefined);
      assert.equal(latest.review_state, "draft");
      const savedHuman = versions.find((version) => version.id === edited.id);
      assert.deepEqual(savedHuman.content, humanContent);
      assert.equal(savedHuman.generated_by, "human");
      assert.equal(savedHuman.review_state, "rejected");
      await assert.rejects(db.query("UPDATE public.case_artifacts SET review_state='approved',reviewed_at=now() WHERE id=$1", [latest.id]), /needs current source information/);
      await assert.rejects(db.query("UPDATE public.case_artifacts SET review_state='approved',reviewed_at=now() WHERE id=$1", [edited.id]), /Superseded artifact/);
    } finally { await db.close(); }
  });
});
